USE ROLE SNOW_ACCOUNTADMINS;
ALTER SESSION SET TIMEZONE = 'America/Chicago';   -- NTZ stamps are Central; a UTC worksheet skews every age by 5-6h

-- A1 (#8) CHANGE RISK baseline before V151
SELECT COUNT(*) AS CHANGE_RISK_ROWS_V088 FROM DBA_MAINT_DB.OVERWATCH.V_SECURITY_EXCEPTION_QUEUE WHERE DOMAIN = 'CHANGE RISK';
-- A2 (#8) what V151 re-surfaces (V151_KEEPS) vs what the rec's substring / NULL-db gate would have re-flooded
WITH d AS (
  SELECT QUERY_TYPE, ROLE_NAME, QUERY_PREVIEW, RISK_LEVEL, EVENT_TS,
         (COALESCE(QUERY_TYPE, '') ILIKE ANY ('%USER%', '%ROLE%', '%POLICY%')
          OR LTRIM(REGEXP_REPLACE(UPPER(COALESCE(QUERY_PREVIEW, '')), '[[:space:]]+', ' '))
             LIKE ANY ('DROP USER %', 'DROP ROLE %', 'DROP DATABASE ROLE %', 'DROP APPLICATION ROLE %',
                       'DROP MASKING POLICY %', 'DROP ROW ACCESS POLICY %', 'DROP NETWORK POLICY %',
                       'DROP PASSWORD POLICY %', 'DROP SESSION POLICY %', 'DROP AUTHENTICATION POLICY %',
                       'DROP AGGREGATION POLICY %', 'DROP PROJECTION POLICY %', 'DROP JOIN POLICY %',
                       'DROP PACKAGES POLICY %', 'DROP PRIVACY POLICY %', 'DROP STORAGE LIFECYCLE POLICY %',
                       'DROP BACKUP POLICY %')) AS V151_KEEPS,
         COALESCE(QUERY_PREVIEW, '') ILIKE '%POLICY%' AS REC_POLICY_SUBSTRING,
         DATABASE_NAME IS NULL AS NULL_DB
  FROM DBA_MAINT_DB.OVERWATCH.FACT_SECURITY_CHANGE
  WHERE CHANGE_KIND = 'DESTRUCTIVE' AND RISK_SCORE >= 70
    AND EVENT_TS >= DATEADD('day', -30, CURRENT_TIMESTAMP())
    AND (UPPER(COALESCE(ROLE_NAME, '')) LIKE 'TF~_%' ESCAPE '~'
         OR (UPPER(COALESCE(DATABASE_NAME, '')) = 'DBA_MAINT_DB' AND UPPER(COALESCE(SCHEMA_NAME, '')) = 'PUBLIC')))
SELECT QUERY_TYPE, V151_KEEPS, REC_POLICY_SUBSTRING, NULL_DB, RISK_LEVEL, COUNT(*) AS EVENTS_30D,
       COUNT_IF(EVENT_TS >= DATEADD('day', -7, CURRENT_TIMESTAMP())) AS EVENTS_7D,
       COUNT(DISTINCT ROLE_NAME) AS ROLES, ANY_VALUE(LEFT(QUERY_PREVIEW, 80)) AS SAMPLE_PREVIEW
FROM d GROUP BY ALL ORDER BY EVENTS_30D DESC;
-- Read V151_KEEPS=TRUE EVENTS_7D against: 1 row = CHANGE RISK Watch (75), 2 = Act (50) + page verdict bad.

-- B1 (#11) rate defect size; B2 historical whole-baseline verifies
SELECT VALUE AS CREDIT_PRICE_SETTING, TRY_TO_NUMBER(VALUE) AS PRE_V153_AUTOBOOK_RATE, TRY_TO_DOUBLE(VALUE) AS TRUE_RATE
FROM DBA_MAINT_DB.OVERWATCH.SETTINGS WHERE KEY = 'CREDIT_PRICE_USD';
SELECT r.VERDICT, l.STATE, COUNT(*) AS ITEMS, SUM(l.VERIFIED_USD) AS VERIFIED_USD, COUNT_IF(r.AFTER_CREDITS_PER_DAY IS NULL) AS AFT_NULL
FROM DBA_MAINT_DB.OVERWATCH.SAVINGS_LEDGER l
JOIN DBA_MAINT_DB.OVERWATCH.WAREHOUSE_CHANGE_REGISTRY r ON r.CHANGE_ID = l.SOURCE_CHANGE_ID
GROUP BY 1, 2 ORDER BY 1, 2;

-- C1-C5 (#12)
SELECT RULE_ID, ENABLED, AUTO_CLEAR_ENABLED, THRESHOLD_NUM, CLEAR_THRESHOLD_NUM FROM DBA_MAINT_DB.OVERWATCH.ALERT_CONFIG
WHERE AUTO_CLEAR_ENABLED OR RULE_ID IN ('SEC_CRED_EXPIRY', 'SEC_NEW_EXPOSURE') ORDER BY 1;   -- only the 3 PERF rules should be TRUE
SELECT KEY, VALUE FROM DBA_MAINT_DB.OVERWATCH.SETTINGS WHERE KEY = 'INCIDENT_AUTO_DECLARE_CRITICAL';
DESCRIBE VIEW SNOWFLAKE.ACCOUNT_USAGE.CREDENTIALS;
SELECT USER_NAME, NAME, TYPE, COUNT(*) AS N, MIN(EXPIRATION_DATE) AS MIN_EXP, MAX(EXPIRATION_DATE) AS MAX_EXP
FROM SNOWFLAKE.ACCOUNT_USAGE.CREDENTIALS GROUP BY 1, 2, 3 HAVING COUNT(*) > 1 ORDER BY N DESC LIMIT 50;
SELECT COUNT(*) AS OPEN_INCIDENTS_ALL_MEMBERS_RESOLVED FROM (
  SELECT i.INCIDENT_ID FROM DBA_MAINT_DB.OVERWATCH.INCIDENTS i
  JOIN DBA_MAINT_DB.OVERWATCH.INCIDENT_MEMBERS m ON m.INCIDENT_ID = i.INCIDENT_ID AND m.MEMBER_KIND = 'ALERT'
  LEFT JOIN DBA_MAINT_DB.OVERWATCH.ALERT_EVENTS e ON e.EVENT_ID = m.REF_ID
  WHERE i.STATUS = 'OPEN' GROUP BY 1
  HAVING COUNT_IF(e.EVENT_ID IS NULL OR e.STATUS <> 'RESOLVED') = 0);   -- first V154 run moves these to MITIGATED

-- D1-D5 (#10/#13) first-run burst preview
SELECT SOURCE_NAME, LAST_LOAD_TS, STATUS,
       ROUND(DATEDIFF('minute', LAST_LOAD_TS, CURRENT_TIMESTAMP()) / 60.0, 1) AS AGE_H,
       IFF(SOURCE_NAME LIKE '%DAILY%' OR SOURCE_NAME LIKE '%METERING%', 30.0, 3.0) AS LIM_H
FROM DBA_MAINT_DB.OVERWATCH.SOURCE_FRESHNESS_STATE
WHERE LAST_LOAD_TS IS NULL
   OR DATEDIFF('minute', LAST_LOAD_TS, CURRENT_TIMESTAMP()) / 60.0 > IFF(SOURCE_NAME LIKE '%DAILY%' OR SOURCE_NAME LIKE '%METERING%', 30.0, 3.0)
ORDER BY AGE_H DESC NULLS FIRST;
SELECT 'MART_TASK_NODE_DAILY' AS T, MAX(LOAD_TS) AS NEWEST, COUNT(*) AS N FROM DBA_MAINT_DB.OVERWATCH.MART_TASK_NODE_DAILY
UNION ALL SELECT 'MART_CLOUD_SVC_DAILY', MAX(LOAD_TS), COUNT(*) FROM DBA_MAINT_DB.OVERWATCH.MART_CLOUD_SVC_DAILY;
SELECT LEASE_NAME, HELD, ACQUIRED_AT FROM DBA_MAINT_DB.OVERWATCH.OW_SENDER_LEASE;
SELECT ROUTE_ID, FAMILY, MIN_SEVERITY, COMPANY_FILTER, ENABLED FROM DBA_MAINT_DB.OVERWATCH.ALERT_ROUTES ORDER BY 1;
SELECT MAX(SNAPSHOT_AT) AS NEWEST_SNAPSHOT, COUNT(DISTINCT WAREHOUSE_NAME) AS WAREHOUSES
FROM DBA_MAINT_DB.OVERWATCH.WAREHOUSE_CONFIG_SNAPSHOT WHERE SNAPSHOT_AT >= DATEADD('hour', -36, CURRENT_TIMESTAMP());

-- E1-E5 (#2) CONTROL_STATUS shape, vocabulary, terminal regularity, volume, grant
SELECT SYSTEM$TYPEOF(TASK_START_DTTM) AS T_START, SYSTEM$TYPEOF(TASK_END_DTTM) AS T_END, MAX(TASK_START_DTTM) AS NEWEST,
       CONVERT_TIMEZONE('America/Chicago', CURRENT_TIMESTAMP())::TIMESTAMP_NTZ AS NOW_CT
FROM ALFA_EDW_PRD.PUBLIC.CONTROL_STATUS WHERE TASK_START_DTTM >= DATEADD('day', -2, CURRENT_TIMESTAMP()) GROUP BY 1, 2;
SELECT UPPER(TASK_STATUS) AS STATUS_WORD, COUNT(*) AS N FROM ALFA_EDW_PRD.PUBLIC.CONTROL_STATUS
WHERE TASK_START_DTTM >= DATEADD('day', -23, CURRENT_TIMESTAMP()) GROUP BY 1 ORDER BY 2 DESC;
SELECT DATE(DATEADD('hour', -12, TASK_START_DTTM)) AS NIGHT,
       COUNT_IF(WORKFLOW_NAME = 'WF_BASE_GW_CLOSEOUT_CTL_DLY') AS STARTER_ROWS,
       COUNT(DISTINCT IFF(WORKFLOW_NAME = 'WF_BASE_RECON_MTRC_CMPSIT_DAILY', TASK_NAME, NULL)) AS TERM_TASKS,
       MAX(IFF(WORKFLOW_NAME = 'WF_BASE_RECON_MTRC_CMPSIT_DAILY', TASK_END_DTTM, NULL)) AS TERM_FINISH
FROM ALFA_EDW_PRD.PUBLIC.CONTROL_STATUS WHERE TASK_START_DTTM >= DATEADD('day', -23, CURRENT_TIMESTAMP())
GROUP BY 1 ORDER BY 1 DESC;   -- any night with STARTER_ROWS > 0 and TERM_TASKS = 0?
SELECT COUNT(*) AS ROWS_23D FROM ALFA_EDW_PRD.PUBLIC.CONTROL_STATUS WHERE TASK_START_DTTM >= DATEADD('day', -23, CURRENT_TIMESTAMP());
SELECT PROCEDURE_OWNER FROM DBA_MAINT_DB.INFORMATION_SCHEMA.PROCEDURES
WHERE PROCEDURE_SCHEMA = 'OVERWATCH' AND PROCEDURE_NAME = 'SP_ALERT_SCAN';   -- the role that must SELECT CONTROL_STATUS

-- F1-F6 (#32)
SELECT TABLE_NAME, IS_TRANSIENT, RETENTION_TIME, ROW_COUNT, BYTES FROM DBA_MAINT_DB.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'OVERWATCH' AND TABLE_TYPE = 'BASE TABLE'
  AND TABLE_NAME IN ('SETTINGS','COMPANY_SCOPE','ALERT_CONFIG','ALERT_EVENTS','ALERT_AUDIT','ACTION_QUEUE','SAVINGS_LEDGER',
                     'DEPARTMENT_MAP','ALERT_ROUTES','REMEDIATION_LOG','USER_PREFS','OBJECT_CHANGE_REGISTRY',
                     'WAREHOUSE_CHANGE_REGISTRY','WAREHOUSE_CONFIG_SNAPSHOT','PIPELINE_SLA_CONFIG','DAILY_DIGEST',
                     'DEPT_BUDGETS','INCIDENTS','INCIDENT_MEMBERS','ACTION_ACTIVITY','EVIDENCE_LINKS','ENTITY_CATALOG',
                     'USER_WATCHLIST','OPTIMIZATION_EXPERIMENTS','SLO_OBJECTIVES') ORDER BY 1;
SHOW DATABASES LIKE 'DBA_MAINT_DB';
SHOW SCHEMAS LIKE 'OVERWATCH' IN DATABASE DBA_MAINT_DB;
SHOW FUTURE GRANTS IN SCHEMA DBA_MAINT_DB.OVERWATCH;
SELECT TABLE_NAME, IS_TRANSIENT, CREATED, ROW_COUNT FROM DBA_MAINT_DB.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'OVERWATCH' AND (TABLE_NAME LIKE '%~_BAK~_%' ESCAPE '~' OR TABLE_NAME LIKE '%OWBAK%') ORDER BY 1;
SELECT LOGGED_AT, ERROR_TYPE, LEFT(ERROR_MESSAGE, 200) AS MSG, CONTEXT FROM DBA_MAINT_DB.OVERWATCH.APP_ERROR_LOG
WHERE PAGE = 'BackupOperatorTables' AND LOGGED_AT >= DATEADD('day', -60, CURRENT_TIMESTAMP()) ORDER BY 1 DESC;
SELECT USER_NAME, ROLE_NAME, QUERY_TYPE, LEFT(QUERY_TEXT, 120) AS QT, START_TIME FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE START_TIME >= DATEADD('day', -8, CURRENT_TIMESTAMP())
  AND QUERY_TEXT ILIKE 'CREATE OR REPLACE TRANSIENT TABLE DBA_MAINT_DB.OVERWATCH.%_BAK_LAST CLONE%'
ORDER BY START_TIME DESC LIMIT 30;   -- F5: expect USER_NAME = 'SYSTEM'

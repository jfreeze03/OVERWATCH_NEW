-- PREFLIGHT_V161.sql -- READ-ONLY preview of what V161 will retire. Changes nothing; run it in Snowsight before
-- applying V161 and paste every result grid back.

USE ROLE SNOW_ACCOUNTADMINS;   -- the role that owns OVERWATCH_BAK (it is owner-only)

-- P1. OVERWATCH_BAK inventory by kind. FOREIGN rows are objects V158 did not create: V161 stops (-20611) on them.
SELECT CASE WHEN TABLE_TYPE = 'BASE TABLE' AND REGEXP_LIKE(TABLE_NAME, '(SETTINGS|COMPANY_SCOPE|ALERT_CONFIG|ALERT_EVENTS|ALERT_AUDIT|ACTION_QUEUE|SAVINGS_LEDGER|DEPARTMENT_MAP|ALERT_ROUTES|REMEDIATION_LOG|USER_PREFS|OBJECT_CHANGE_REGISTRY|WAREHOUSE_CHANGE_REGISTRY|WAREHOUSE_CONFIG_SNAPSHOT|PIPELINE_SLA_CONFIG|DAILY_DIGEST|DEPT_BUDGETS|INCIDENTS|INCIDENT_MEMBERS|ACTION_ACTIVITY|EVIDENCE_LINKS|ENTITY_CATALOG|USER_WATCHLIST|OPTIMIZATION_EXPERIMENTS|SLO_OBJECTIVES)_OWBAK_[DW][0-9]{8}')
                 THEN 'GENERATION_' || SUBSTR(TABLE_NAME, LENGTH(TABLE_NAME) - 8, 1)
            WHEN TABLE_TYPE = 'BASE TABLE' AND TABLE_NAME IN ('OPERATOR_BACKUP_LOG', 'SETTINGS_BAK_LAST', 'COMPANY_SCOPE_BAK_LAST', 'ALERT_CONFIG_BAK_LAST',
                                                             'ALERT_EVENTS_BAK_LAST', 'ALERT_AUDIT_BAK_LAST', 'ACTION_QUEUE_BAK_LAST', 'SAVINGS_LEDGER_BAK_LAST',
                                                             'DEPARTMENT_MAP_BAK_LAST', 'ALERT_ROUTES_BAK_LAST', 'REMEDIATION_LOG_BAK_LAST', 'USER_PREFS_BAK_LAST',
                                                             'OBJECT_CHANGE_REGISTRY_BAK_LAST', 'WAREHOUSE_CHANGE_REGISTRY_BAK_LAST', 'WAREHOUSE_CONFIG_SNAPSHOT_BAK_LAST', 'PIPELINE_SLA_CONFIG_BAK_LAST',
                                                             'DAILY_DIGEST_BAK_LAST', 'DEPT_BUDGETS_BAK_LAST', 'INCIDENTS_BAK_LAST', 'INCIDENT_MEMBERS_BAK_LAST',
                                                             'ACTION_ACTIVITY_BAK_LAST', 'EVIDENCE_LINKS_BAK_LAST', 'ENTITY_CATALOG_BAK_LAST', 'USER_WATCHLIST_BAK_LAST',
                                                             'OPTIMIZATION_EXPERIMENTS_BAK_LAST', 'SLO_OBJECTIVES_BAK_LAST')
                 THEN 'MOVED_BY_A_PARTIAL_V161'
            ELSE 'FOREIGN' END AS KIND,
       COUNT(*) AS OBJECTS,
       MIN(TABLE_NAME) AS FIRST_NAME, MAX(TABLE_NAME) AS LAST_NAME,
       SUM(BYTES) AS BYTES
  FROM DBA_MAINT_DB.INFORMATION_SCHEMA.TABLES
 WHERE TABLE_SCHEMA = 'OVERWATCH_BAK'
 GROUP BY 1
 ORDER BY 1;

-- P2. Non-table objects in OVERWATCH_BAK: expect every count 0 (V161 stops (-20611) otherwise; SHOW OBJECTS
--     would list only tables and views). Tasks, streams and alerts are counted from a database-wide SHOW, so a
--     missing or unreadable schema reads 0 instead of stopping the grids below. The schema's owner is the role
--     that must apply V161.
SHOW SCHEMAS LIKE 'OVERWATCH_BAK' IN DATABASE DBA_MAINT_DB;
SELECT 'STAGES' AS KIND, COUNT(*) AS OBJECTS FROM DBA_MAINT_DB.INFORMATION_SCHEMA.STAGES WHERE STAGE_SCHEMA = 'OVERWATCH_BAK'
UNION ALL
SELECT 'SEQUENCES', COUNT(*) FROM DBA_MAINT_DB.INFORMATION_SCHEMA.SEQUENCES WHERE SEQUENCE_SCHEMA = 'OVERWATCH_BAK'
UNION ALL
SELECT 'FILE_FORMATS', COUNT(*) FROM DBA_MAINT_DB.INFORMATION_SCHEMA.FILE_FORMATS WHERE FILE_FORMAT_SCHEMA = 'OVERWATCH_BAK'
UNION ALL
SELECT 'FUNCTIONS', COUNT(*) FROM DBA_MAINT_DB.INFORMATION_SCHEMA.FUNCTIONS WHERE FUNCTION_SCHEMA = 'OVERWATCH_BAK'
UNION ALL
SELECT 'PROCEDURES', COUNT(*) FROM DBA_MAINT_DB.INFORMATION_SCHEMA.PROCEDURES WHERE PROCEDURE_SCHEMA = 'OVERWATCH_BAK'
UNION ALL
SELECT 'PIPES', COUNT(*) FROM DBA_MAINT_DB.INFORMATION_SCHEMA.PIPES WHERE PIPE_SCHEMA = 'OVERWATCH_BAK'
ORDER BY 1;
SHOW TASKS IN DATABASE DBA_MAINT_DB;
SELECT COUNT(*) AS OVERWATCH_BAK_TASKS FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())) WHERE "schema_name" = 'OVERWATCH_BAK';
SHOW STREAMS IN DATABASE DBA_MAINT_DB;
SELECT COUNT(*) AS OVERWATCH_BAK_STREAMS FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())) WHERE "schema_name" = 'OVERWATCH_BAK';
SHOW ALERTS IN DATABASE DBA_MAINT_DB;
SELECT COUNT(*) AS OVERWATCH_BAK_ALERTS FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())) WHERE "schema_name" = 'OVERWATCH_BAK';

-- P3. The 26 names V161 moves out of OVERWATCH: expect one RETIRED_BY_V161 row reading TABLES 26,
--     TRANSIENT_TABLES 25 once V158 has run on a Sunday (the ledger is the one permanent table), plus a
--     MANUAL_CLONE_KEPT row if any manual <T>_BAK_<yyyymmdd> clones exist: V161 leaves those alone, and that
--     row's TABLES count is the baseline for PART B item 5.
SELECT IFF(TABLE_NAME IN ('OPERATOR_BACKUP_LOG', 'SETTINGS_BAK_LAST', 'COMPANY_SCOPE_BAK_LAST', 'ALERT_CONFIG_BAK_LAST',
                          'ALERT_EVENTS_BAK_LAST', 'ALERT_AUDIT_BAK_LAST', 'ACTION_QUEUE_BAK_LAST', 'SAVINGS_LEDGER_BAK_LAST',
                          'DEPARTMENT_MAP_BAK_LAST', 'ALERT_ROUTES_BAK_LAST', 'REMEDIATION_LOG_BAK_LAST', 'USER_PREFS_BAK_LAST',
                          'OBJECT_CHANGE_REGISTRY_BAK_LAST', 'WAREHOUSE_CHANGE_REGISTRY_BAK_LAST', 'WAREHOUSE_CONFIG_SNAPSHOT_BAK_LAST', 'PIPELINE_SLA_CONFIG_BAK_LAST',
                          'DAILY_DIGEST_BAK_LAST', 'DEPT_BUDGETS_BAK_LAST', 'INCIDENTS_BAK_LAST', 'INCIDENT_MEMBERS_BAK_LAST',
                          'ACTION_ACTIVITY_BAK_LAST', 'EVIDENCE_LINKS_BAK_LAST', 'ENTITY_CATALOG_BAK_LAST', 'USER_WATCHLIST_BAK_LAST',
                          'OPTIMIZATION_EXPERIMENTS_BAK_LAST', 'SLO_OBJECTIVES_BAK_LAST'),
           'RETIRED_BY_V161', 'MANUAL_CLONE_KEPT') AS KIND,
       COUNT(*) AS TABLES, COUNT_IF(IS_TRANSIENT = 'YES') AS TRANSIENT_TABLES,
       MIN(TABLE_NAME) AS FIRST_NAME, MAX(TABLE_NAME) AS LAST_NAME
  FROM DBA_MAINT_DB.INFORMATION_SCHEMA.TABLES
 WHERE TABLE_SCHEMA = 'OVERWATCH' AND TABLE_TYPE = 'BASE TABLE'
   AND (TABLE_NAME IN ('OPERATOR_BACKUP_LOG', 'SETTINGS_BAK_LAST', 'COMPANY_SCOPE_BAK_LAST', 'ALERT_CONFIG_BAK_LAST',
                        'ALERT_EVENTS_BAK_LAST', 'ALERT_AUDIT_BAK_LAST', 'ACTION_QUEUE_BAK_LAST', 'SAVINGS_LEDGER_BAK_LAST',
                        'DEPARTMENT_MAP_BAK_LAST', 'ALERT_ROUTES_BAK_LAST', 'REMEDIATION_LOG_BAK_LAST', 'USER_PREFS_BAK_LAST',
                        'OBJECT_CHANGE_REGISTRY_BAK_LAST', 'WAREHOUSE_CHANGE_REGISTRY_BAK_LAST', 'WAREHOUSE_CONFIG_SNAPSHOT_BAK_LAST', 'PIPELINE_SLA_CONFIG_BAK_LAST',
                        'DAILY_DIGEST_BAK_LAST', 'DEPT_BUDGETS_BAK_LAST', 'INCIDENTS_BAK_LAST', 'INCIDENT_MEMBERS_BAK_LAST',
                        'ACTION_ACTIVITY_BAK_LAST', 'EVIDENCE_LINKS_BAK_LAST', 'ENTITY_CATALOG_BAK_LAST', 'USER_WATCHLIST_BAK_LAST',
                        'OPTIMIZATION_EXPERIMENTS_BAK_LAST', 'SLO_OBJECTIVES_BAK_LAST')
        OR REGEXP_LIKE(TABLE_NAME, '.+_BAK_[0-9]{8}'))
 GROUP BY 1
 ORDER BY 1;

-- P4. The retention SETTINGS, the freshness row and any open stale event V161 deletes / closes.
SELECT 'SETTING ' || KEY AS ITEM, VALUE, NULL AS NEWEST
  FROM DBA_MAINT_DB.OVERWATCH.SETTINGS
 WHERE KEY IN ('BACKUP_KEEP_DAILY', 'BACKUP_KEEP_WEEKLY')
UNION ALL
SELECT 'FRESHNESS ' || SOURCE_NAME, STATUS, LAST_LOAD_TS::VARCHAR
  FROM DBA_MAINT_DB.OVERWATCH.SOURCE_FRESHNESS_STATE
 WHERE SOURCE_NAME = 'OPERATOR_BACKUP_DAILY'
UNION ALL
SELECT 'OPEN STALE EVENT ' || STATUS, COUNT(*)::VARCHAR, MAX(DEDUPE_KEY)
  FROM DBA_MAINT_DB.OVERWATCH.ALERT_EVENTS
 WHERE RULE_ID = 'OPS_PIPELINE_DEGRADED'
   AND STARTSWITH(DEDUPE_KEY, 'OPS_PIPELINE_DEGRADED|STALE|OPERATOR_BACKUP_DAILY|')
   AND STATUS IN ('OPEN', 'ACK', 'SNOOZED')
 GROUP BY STATUS
ORDER BY 1;

-- P5. The task's recent runs and its next scheduled one: apply V161 away from a run (not ~05:05-05:20 Central).
SELECT NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME, LEFT(ERROR_MESSAGE, 120) AS ERROR_MESSAGE
  FROM TABLE(DBA_MAINT_DB.INFORMATION_SCHEMA.TASK_HISTORY(
           SCHEDULED_TIME_RANGE_START => DATEADD('hour', -30, CURRENT_TIMESTAMP()),
           TASK_NAME => 'TASK_BACKUP_OPERATOR'))
 ORDER BY SCHEDULED_TIME DESC;

-- P6. LAST, on its own: the backup ledger. PRUNED / PRUNE_FAILED expected 0 (no prune has run, so the view
--     carve-out V161 removes never matched a row). Once V161 has moved or dropped the ledger (a partial or
--     finished V161; P1 shows a moved one), this one statement errors; the grids above are unaffected.
SELECT ACTION, COUNT(*) AS ROWS_, MAX(LOGGED_AT) AS NEWEST
  FROM DBA_MAINT_DB.OVERWATCH.OPERATOR_BACKUP_LOG
 GROUP BY ACTION
 ORDER BY 1;
